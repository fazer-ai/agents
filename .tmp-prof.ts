import { PrismaPg } from "@prisma/adapter-pg";
import { PrismaClient } from "@/../generated/prisma/client";
import { metricsPoolOptions } from "@/api/lib/pool-options";
import { alignedDays, BLOCK_SECTIONS, WindowLoad } from "@/modules/analytics/rollup/engine";
import { figuresOf } from "@/modules/analytics/rollup/figures";
import { BLOCKS } from "@/modules/analytics/rollup/stream";
const url = process.env.DATABASE_URL!.replace("${POSTGRES_PORT}", "5432");
const db = new PrismaClient({ adapter: new PrismaPg(metricsPoolOptions(url)), log: [{ level: "query", emit: "event" }] });
const t0 = performance.now();
db.$on("query", (e) => { if (e.duration > 30) console.log(((performance.now() - t0) / 1000).toFixed(2), `${e.duration}ms`, e.query.replace(/\s+/g, " ").slice(0, 140)); });
const ctx = { tenantId: 1n, userId: null, role: "TENANT_ADMIN" } as const;
const tz = "America/Sao_Paulo";
const today = new Intl.DateTimeFormat("en-CA", { timeZone: tz }).format(new Date());
const t = new Date(`${today}T03:00:00Z`).getTime();
const f = { since: new Date(t - 364 * 86400000), until: new Date(t + 86400000), tz, source: "inbox" as const };
const sections = [...new Set(BLOCKS.flatMap((b) => BLOCK_SECTIONS[b]))];
const load = new WindowLoad(ctx as never, f as never, sections as never, alignedDays(f as never)!, db);
const lap = (l: string) => console.log(((performance.now() - t0) / 1000).toFixed(2), "==", l);
await load.prepare(); lap("prepare");
await figuresOf(ctx as never, load, BLOCKS, null, db); lap("figures");
while (await load.step()) lap(`step`);
await figuresOf(ctx as never, load, BLOCKS, null, db); lap("figures");
await db.$disconnect();
