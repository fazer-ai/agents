export function ServiceLogo({
  service,
  className,
}: {
  service?: string;
  className?: string;
}) {
  const mark = service ? BRAND_PATHS[service] : undefined;
  if (!mark) return <KeyRound className={className} aria-hidden="true" />;
  if (typeof mark !== "string" && "paths" in mark) {
    return (
      <svg
        viewBox={mark.viewBox}
        className={className}
        aria-hidden="true"
        role="img"
      >
        {mark.paths.map((p) => (
          <path key={p.d} d={p.d} fill={p.fill} />
        ))}
      </svg>
    );
  }
  const path = typeof mark === "string" ? mark : mark.path;
  const viewBox = typeof mark === "string" ? "0 0 24 24" : mark.viewBox;
  return (
    <svg
      viewBox={viewBox}
      className={className}
      fill="currentColor"
      aria-hidden="true"
      role="img"
    >
      <path d={path} />
    </svg>
  );
}
